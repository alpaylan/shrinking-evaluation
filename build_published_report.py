# JavaScript executed after etna's own boot finishes filling METRICS.
# Polls until METRICS is populated, then renders one heatmap per workload
# and wires click-to-drill-down handlers for the detail panels.
BROWSER_JS = r"""
<script>
(() => {
  const EXCLUDED_STRATEGIES = new Set(['Size']);

  function treeDepth(s) {
    let d = 0, max = 0;
    for (let i = 0; i < s.length; i++) {
      const c = s[i];
      if (c === '(') { d++; if (d > max) max = d; }
      else if (c === ')') d--;
    }
    return max;
  }

  function parseTime(s) {
    if (s == null) return null;
    const m = String(s).trim().match(/^([0-9.]+)\s*s?$/);
    return m ? parseFloat(m[1]) : null;
  }

  function fmtTime(s) {
    if (s == null) return '—';
    if (s >= 1) return s.toFixed(2) + 's';
    if (s >= 1e-3) return (s * 1e3).toFixed(1) + 'ms';
    return Math.round(s * 1e6) + 'µs';
  }

  function median(arr) {
    if (!arr.length) return null;
    const s = arr.slice().sort((a, b) => a - b);
    const m = s.length >> 1;
    return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
  }

  // viridis-ish: dark purple → teal → yellow.
  function colorFor(t) {
    if (t == null || isNaN(t)) return 'var(--tx-surface-2)';
    t = Math.max(0, Math.min(1, t));
    const stops = [
      [ 68,  1, 84],   // dark purple
      [ 59, 82,139],   // blue
      [ 33,144,141],   // teal
      [ 94,201, 98],   // green
      [253,231, 37],   // yellow
    ];
    const x = t * (stops.length - 1);
    const i = Math.floor(x);
    const f = x - i;
    const a = stops[i];
    const b = stops[Math.min(i + 1, stops.length - 1)];
    const r = Math.round(a[0] + (b[0] - a[0]) * f);
    const g = Math.round(a[1] + (b[1] - a[1]) * f);
    const bl = Math.round(a[2] + (b[2] - a[2]) * f);
    return `rgb(${r},${g},${bl})`;
  }

  function escapeHtml(s) {
    return String(s)
      .replaceAll('&', '&amp;')
      .replaceAll('<', '&lt;')
      .replaceAll('>', '&gt;')
      .replaceAll('"', '&quot;');
  }

  // Turn a paren-and-comma soup into an indented tree. Each non-first child
  // of a `(` goes on its own indented line; atoms-only inputs pass through.
  function prettyPrint(s) {
    if (typeof s !== 'string' || !s.includes('(')) return String(s);
    const tokens = [];
    let i = 0;
    while (i < s.length) {
      const c = s[i];
      if (c === '(' || c === ')') { tokens.push(c); i++; }
      else if (c === ',' || /\s/.test(c)) { i++; }
      else {
        let j = i;
        while (j < s.length && s[j] !== '(' && s[j] !== ')' && s[j] !== ',' && !/\s/.test(s[j])) j++;
        tokens.push(s.slice(i, j));
        i = j;
      }
    }
    let out = '';
    let depth = 0;
    let prev = null;
    for (const t of tokens) {
      if (t === '(') {
        if (prev !== null && prev !== '(') out += '\n' + '  '.repeat(depth);
        out += '(';
        depth++;
      } else if (t === ')') {
        depth = Math.max(0, depth - 1);
        out += ')';
      } else {
        if (prev === '(' || prev === null) out += t;
        else out += '\n' + '  '.repeat(depth) + t;
      }
      prev = t;
    }
    return out;
  }

  // Build per-cell trial buckets keyed by [workload, mutation, property, strategy].
  function bucket(metrics) {
    const out = new Map();
    for (const m of metrics) {
      if (m.status !== 'Failed') continue;
      if (!m.counterexample) continue;
      if (EXCLUDED_STRATEGIES.has(m.strategy)) continue;
      const wl = m.workload;
      const mut = (m.mutations || [null])[0];
      const prop = m.property;
      const strat = m.strategy;
      const key = wl + '\x00' + mut + '\x00' + prop + '\x00' + strat;
      let arr = out.get(key);
      if (!arr) { arr = []; out.set(key, arr); }
      arr.push({
        workload: wl, mutation: mut, property: prop, strategy: strat,
        trial: m.trial,
        counterexample: m.counterexample,
        depth: treeDepth(m.counterexample),
        time: parseTime(m.time),
        tests: m.tests,
        discards: m.discards,
      });
    }
    return out;
  }

  function renderHeatmap(mountEl, workload, buckets) {
    const cells = new Map();
    for (const [key, trials] of buckets) {
      const [wl, mut, prop, strat] = key.split('\x00');
      if (wl !== workload) continue;
      cells.set(`${mut}\x00${prop}\x00${strat}`, trials);
    }
    if (!cells.size) {
      mountEl.innerHTML = '<p class="cx-loading">No data for this workload.</p>';
      return;
    }
    const bugs = [...new Set([...cells.keys()].map(k => k.split('\x00').slice(0, 2).join('\x00')))].sort();
    const strats = [...new Set([...cells.keys()].map(k => k.split('\x00')[2]))].sort();

    // Per-workload color scale over the median depth across populated cells.
    const medians = [];
    for (const trials of cells.values()) {
      const d = median(trials.map(t => t.depth));
      if (d != null) medians.push(d);
    }
    const lo = Math.min(...medians), hi = Math.max(...medians);
    const norm = (v) => (hi === lo ? 0.5 : (v - lo) / (hi - lo));

    const table = document.createElement('table');
    table.className = 'cx-heatmap-table';
    let thead = '<thead><tr><th></th>';
    for (const s of strats) thead += `<th>${escapeHtml(s)}</th>`;
    thead += '</tr></thead>';
    table.innerHTML = thead;

    const tbody = document.createElement('tbody');
    for (const bug of bugs) {
      const [mut, prop] = bug.split('\x00');
      const tr = document.createElement('tr');
      const th = document.createElement('th');
      th.className = 'cx-row-label';
      th.title = `${mut} / ${prop}`;
      th.textContent = `${mut} / ${prop}`;
      tr.appendChild(th);
      for (const strat of strats) {
        const td = document.createElement('td');
        const trials = cells.get(`${mut}\x00${prop}\x00${strat}`);
        if (trials && trials.length) {
          const medDepth = median(trials.map(t => t.depth));
          const medTime = median(trials.map(t => t.time).filter(t => t != null));
          td.textContent = String(medDepth);
          const t = norm(medDepth);
          td.style.background = colorFor(t);
          td.style.color = t > 0.55 ? '#000' : '#fff';
          td.title = `${strat}\nn=${trials.length} · median depth ${medDepth} · median time ${fmtTime(medTime)}`;
          td.classList.add('cx-cell-data');
          td.dataset.workload = workload;
          td.dataset.mutation = mut;
          td.dataset.property = prop;
          td.dataset.strategy = strat;
          td.addEventListener('click', () => {
            renderDetail(workload, mut, prop, strat, trials, td);
          });
        } else {
          td.textContent = '—';
          td.className = 'cx-cell-empty';
          td.title = `${strat}\nNo Failed result within 60s timeout`;
        }
        tr.appendChild(td);
      }
      tbody.appendChild(tr);
    }
    table.appendChild(tbody);
    mountEl.innerHTML = '';
    mountEl.appendChild(table);
  }

  function renderDetail(workload, mutation, property, strategy, trials, sourceCell) {
    const detail = document.querySelector(`[data-cx-detail="${workload}"]`);
    if (!detail) return;
    const sorted = trials.slice().sort((a, b) => (a.trial ?? 0) - (b.trial ?? 0));
    const medDepth = median(sorted.map(t => t.depth));
    const medTime = median(sorted.map(t => t.time).filter(t => t != null));

    let html = `
      <header class="cx-detail-header">
        <h4>${escapeHtml(workload)} · ${escapeHtml(mutation)} · ${escapeHtml(property)} · ${escapeHtml(strategy)}</h4>
        <p class="cx-detail-meta">n=${sorted.length} trials · median depth ${medDepth} · median time ${fmtTime(medTime)}</p>
      </header>
    `;
    for (const t of sorted) {
      html += `
        <div class="cx-trial">
          <div class="cx-trial-meta">trial ${t.trial ?? '?'} · depth ${t.depth} · tests ${t.tests ?? '?'} · discards ${t.discards ?? 0} · time ${fmtTime(t.time)}</div>
          <pre class="cx-text">${escapeHtml(prettyPrint(t.counterexample))}</pre>
        </div>
      `;
    }
    detail.innerHTML = html;
    // Highlight selected cell.
    document.querySelectorAll('.cx-cell-selected').forEach(el => el.classList.remove('cx-cell-selected'));
    if (sourceCell) sourceCell.classList.add('cx-cell-selected');
    detail.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
    detail.classList.remove('cx-detail-flash');
    void detail.offsetWidth;  // restart animation
    detail.classList.add('cx-detail-flash');
  }

  function init() {
    if (!Array.isArray(METRICS) || !METRICS.length) {
      setTimeout(init, 100);
      return;
    }
    const buckets = bucket(METRICS);
    document.querySelectorAll('[data-cx-heatmap]').forEach(el => {
      renderHeatmap(el, el.dataset.cxHeatmap, buckets);
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
</script>
"""


