# Stable end-of-content anchor: rawdata view's pagination + its closing
# </div> + the .content container's closing </div>. Replacing this anchor
# with itself-minus-final-</div> + new view divs + </div> inserts the new
# views inside .content right after the rawdata view.
CONTENT_ANCHOR = (
    '<div class="pagination" id="raw-pagination"></div>\n'
    "  </div>\n"
    "</div>"
)


def main():
    if not REPORT.exists():
        raise SystemExit(f"missing {REPORT} — run `etna experiment report` first")
    if not SUMMARY.exists():
        raise SystemExit(f"missing {SUMMARY} — run AnalyzeShrinking.py first")

    html = REPORT.read_text()

    # 1. Inject CSS in <head>.
    html = html.replace("</head>", ANALYSIS_CSS + BROWSER_CSS + "</head>", 1)

    # 2. Inject two new buttons into the existing <nav>.
    if "</nav>" not in html:
        raise SystemExit("could not find </nav> in report — has the template changed?")
    html = html.replace("</nav>", NAV_INJECT, 1)

    # 3. Inject two new <div class="view"> blocks inside <div class="content">,
    #    right after the rawdata view, so the existing nav click handler picks
    #    them up via document.getElementById('view-' + dataset.view).
    if CONTENT_ANCHOR not in html:
        raise SystemExit("could not find the content anchor in report — has the template changed?")
    new_views = (
        '<div class="pagination" id="raw-pagination"></div>\n'
        "  </div>\n"
        f'  <div class="view" id="view-analysis">{build_section()}</div>\n'
        f'  <div class="view" id="view-browser">{build_browser_section()}</div>\n'
        "</div>"
    )
    html = html.replace(CONTENT_ANCHOR, new_views, 1)

    # 4. Inject browser JS at the end so it runs after etna's METRICS load.
    html = html.replace("</body>", BROWSER_JS + "</body>", 1)

    OUT.write_text(html)
    size_kb = OUT.stat().st_size / 1024
    print(f"wrote {OUT} ({size_kb:,.0f} KB)")


if __name__ == "__main__":
    main()
