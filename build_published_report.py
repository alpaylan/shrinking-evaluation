def png_data_uri(path: Path) -> str:
    return "data:image/png;base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def md_table_to_html(lines: list[str]) -> str:
    """Convert a single GFM-style table (header / divider / rows) to HTML."""
    if len(lines) < 2:
        return ""
    cells = [
        [c.strip() for c in row.strip().strip("|").split("|")]
        for row in lines
    ]
    # cells[0] = header, cells[1] = divider, rest = body
    head = cells[0]
    body = cells[2:]
    out = ['<table class="analysis-table">', "<thead><tr>"]
    out += [f"<th>{h}</th>" for h in head]
    out.append("</tr></thead><tbody>")
    for row in body:
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in row) + "</tr>")
    out.append("</tbody></table>")
    return "".join(out)


def render_summary_md(md: str) -> str:
    """
    Hand-rolled, sufficient-for-this-doc Markdown renderer.
    Handles: # / ## headings, paragraphs, GFM tables, **bold**, `code`, `-` lists.
    """
    html_parts: list[str] = []
    buf_table: list[str] = []
    buf_list: list[str] = []
    buf_para: list[str] = []

    def flush_table():
        if buf_table:
            html_parts.append(md_table_to_html(buf_table))
            buf_table.clear()

    def flush_list():
        if buf_list:
            html_parts.append("<ul>" + "".join(f"<li>{item}</li>" for item in buf_list) + "</ul>")
            buf_list.clear()

    def flush_para():
        if buf_para:
            html_parts.append("<p>" + " ".join(buf_para) + "</p>")
            buf_para.clear()

    def flush_all():
        flush_table()
        flush_list()
        flush_para()

    def inline(s: str) -> str:
        s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
        s = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", s)
        return s

    for raw in md.splitlines():
        line = raw.rstrip()
        if line.startswith("# "):
            flush_all()
            html_parts.append(f"<h2>{inline(line[2:].strip())}</h2>")
        elif line.startswith("## "):
            flush_all()
            html_parts.append(f"<h3>{inline(line[3:].strip())}</h3>")
        elif line.startswith("|"):
            flush_list()
            flush_para()
            buf_table.append(line)
        elif line.startswith("- "):
            flush_table()
            flush_para()
            buf_list.append(inline(line[2:].strip()))
        elif not line.strip():
            flush_all()
        else:
            flush_table()
            flush_list()
            buf_para.append(inline(line.strip()))
    flush_all()
    return "\n".join(html_parts)


def build_section() -> str:
    summary_html = render_summary_md(SUMMARY.read_text())
    figs_html: list[str] = []
    for w in WORKLOADS:
        figs_html.append(f'<h3>{w}</h3>')
        for kind, caption in FIGURE_KINDS:
            path = FIGURES / f"{w}_{kind}.png"
            if not path.exists():
                continue
            figs_html.append(
                f'<figure class="analysis-figure">'
                f'<img alt="{w} {kind}" src="{png_data_uri(path)}">'
                f'<figcaption>{caption}</figcaption>'
                f'</figure>'
            )
    return f"""
<section id="shrinking-analysis" class="analysis-section">
  <header><h1>Counterexample size + time analysis</h1></header>
  <div class="analysis-summary">{summary_html}</div>
  <div class="analysis-figures">{''.join(figs_html)}</div>
</section>
"""


