def build_browser_section() -> str:
    """Skeleton HTML for the interactive counterexample browser. The heatmap
    bodies are filled in at runtime by BROWSER_JS, which reads from the
    already-decompressed global METRICS array that etna's report populates.
    """
    blocks = []
    for w in WORKLOADS:
        blocks.append(
            f'<div class="cx-workload">'
            f'<h3>{w}</h3>'
            f'<div class="cx-heatmap" data-cx-heatmap="{w}">'
            f'<p class="cx-loading">Loading metrics…</p>'
            f'</div>'
            f'<div class="cx-detail" data-cx-detail="{w}">'
            f'<p class="cx-detail-empty">Click a heatmap cell to view its counterexamples.</p>'
            f'</div>'
            f'</div>'
        )
    return f"""
<section id="counterexample-browser" class="cx-browser">
  <header><h1>Counterexample browser</h1></header>
  <p class="cx-intro">Click any heatmap cell to drill into the actual counterexamples for that
  (workload, mutation, property, strategy) combo, pretty-printed across all 10 trials. Cells
  are coloured by median counterexample tree depth (lower is better). The <code>Size</code>
  strategy is excluded for the same reason as the static analysis above.</p>
  {''.join(blocks)}
</section>
"""


